// pickLang(['de-CH', 'en']) -> 'de'. First supported language in the visitor's preference list; English for everyone else.
export function pickLang(preferred = [], supported = LANGS, fallback = 'en') {
  for (const tag of preferred) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (supported.includes(base)) return base;
  }
  return fallback;
}

